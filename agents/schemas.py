"""Strict Pydantic v2 data models for Project Argon.

Enforces zero-unstructured-text handoffs between Ingestion, Vision, Director,
Audio, and VFX agents, strictly adhering to Section 3 of the System Directive.
"""

from __future__ import annotations
from typing import List, Literal, Optional
from datetime import datetime, timezone
from pydantic import BaseModel, Field
from config.settings import seconds_to_ticks, seconds_to_ticks_str


class WordToken(BaseModel):
    """Timestamped single spoken word from Faster-Whisper."""
    word: str
    start_sec: float
    end_sec: float
    confidence: float

    @property
    def start_ticks(self) -> int:
        return seconds_to_ticks(self.start_sec)

    @property
    def end_ticks(self) -> int:
        return seconds_to_ticks(self.end_sec)


class SilenceOrFillerSpan(BaseModel):
    """Detected dead air, vocal hesitation, retake, or breath."""
    start_sec: float
    end_sec: float
    duration_sec: float
    kind: Literal["dead_air", "um_uh_filler", "retake_duplicate", "breath"]

    @property
    def start_ticks(self) -> int:
        return seconds_to_ticks(self.start_sec)

    @property
    def end_ticks(self) -> int:
        return seconds_to_ticks(self.end_sec)


class VisualShotAnalysis(BaseModel):
    """Multimodal vision evaluation of a detected shot from Llama-3.2-90B-Vision."""
    shot_id: int
    source_file: str
    start_sec: float
    end_sec: float
    shot_scale: Literal["ECU", "CU", "MCU", "MS", "WS", "EWS", "SCREEN_CAPTURE"]
    camera_motion: Literal["static", "pan", "tilt", "zoom_in", "zoom_out", "handheld_shake"]
    visual_quality_score: int = Field(ge=1, le=10)
    is_usable: bool
    subject_emotion: str
    b_roll_tags: List[str] = Field(default_factory=list)
    summary: str


class MediaFileAnalysis(BaseModel):
    """Complete multimodal manifest of an ingested media file."""
    file_id: str
    master_filepath: str
    proxy_filepath: str
    fps: float
    width: int
    height: int
    duration_sec: float
    role: Literal["A_ROLL_MAIN", "B_ROLL", "SCREEN_RECORDING", "MUSIC", "SFX"]
    words: List[WordToken] = Field(default_factory=list)
    bad_spans: List[SilenceOrFillerSpan] = Field(default_factory=list)
    shots: List[VisualShotAnalysis] = Field(default_factory=list)


class MediaAnalysisManifest(BaseModel):
    """Aggregate manifest of all analyzed files for a video project."""
    manifest_id: str
    project_name: str
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    files: List[MediaFileAnalysis] = Field(default_factory=list)


class KeyframeTransform(BaseModel):
    """Spatial and scale transform keyframe."""
    time_offset_sec: float
    scale: float = 100.0
    pos_x: float = 0.5
    pos_y: float = 0.5


class TimelineClipAction(BaseModel):
    """Atomic timeline mutation directive for Premiere Pro or After Effects."""
    action_id: int
    track_type: Literal["VIDEO", "AUDIO"]
    track_index: int  # 0 = V1/A1, 1 = V2/A2, etc.
    source_file_id: str
    master_filepath: str
    src_in_sec: float
    src_out_sec: float
    timeline_in_sec: float
    j_l_cut_audio_offset_sec: float = 0.0  # Negative = J-cut (audio leads), Positive = L-cut
    keyframes: List[KeyframeTransform] = Field(default_factory=list)
    lumetri_lut_path: Optional[str] = None
    transition_in: Optional[Literal["cut", "cross_dissolve", "dip_to_black", "whip_pan"]] = "cut"
    ae_dynamic_text: Optional[str] = None  # Triggers After Effects callout/subtitle generation
    reasoning: str

    @property
    def src_in_ticks_str(self) -> str:
        return seconds_to_ticks_str(self.src_in_sec)

    @property
    def src_out_ticks_str(self) -> str:
        return seconds_to_ticks_str(self.src_out_sec)

    @property
    def timeline_in_ticks_str(self) -> str:
        return seconds_to_ticks_str(self.timeline_in_sec)


class MasterEditPlan(BaseModel):
    """Complete edit decision list and timeline blueprint generated by Director Agent."""
    plan_id: str
    project_title: str
    timeline_duration_sec: float
    actions: List[TimelineClipAction] = Field(default_factory=list)
